export function getGuide(slug: string) {
  return guides.find((guide) => guide.slug === slug);
}

/** Guides to surface on a product page by category / brand. */
export function guidesForProduct(product: {
  category: "station" | "generator" | "inverter";
  brand: string;
}) {
  const brand = product.brand.toLowerCase();
  const slugs: string[] = ["vidklyuchennya-svitla"];
  if (product.category === "station") {
    slugs.push(
      "zaryadna-stantsiya",
      "portatyvna-zaryadna-stantsiya",
      "zaryadna-stantsiya-dlya-kvartyry",
    );
  }
  if (product.category === "generator") {
    slugs.push("generator", "benzynovyy-generator", "generator-dlya-domu");
  }
  if (product.category === "inverter") {
    slugs.push(
      "invertor",
      "invertor-2-kvt",
      "invertor-3-kvt",
      "invertor-5-kvt",
      "invertor-12-220",
      "akumulyator-dlya-invertora",
    );
  }
  if (brand.includes("ecoflow")) slugs.push("ecoflow", "ecoflow-delta-2");
  if (brand.includes("bluetti")) slugs.push("bluetti");
  if (brand.includes("anker")) slugs.push("zaryadna-stantsiya-anker");
  if (brand.includes("deye")) slugs.push("invertor-deye", "deye-6-kvt");
  if (product.category === "inverter") {
    slugs.push("akumulyator-lifepo4", "invertor-10-kvt");
  }
  return [...new Set(slugs)]
    .map((slug) => getGuide(slug))
    .filter((item): item is Guide => Boolean(item));
}

export function relatedGuides(guide: Guide) {
  return guide.relatedSlugs
    .map((slug) => getGuide(slug))
    .filter((item): item is Guide => Boolean(item));
}

export const guidesByVolume = [...guides].sort(
  (a, b) => b.searchVolume - a.searchVolume,
);
